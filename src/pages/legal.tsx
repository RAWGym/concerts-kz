export async function generateMetadata({
  params,
}: PageProps<"/[locale]/legal/[doc]">): Promise<Metadata> {
  const { doc } = await params;
  return { title: docs[doc]?.title };
}

export default async function LegalPage({
  params,
}: PageProps<"/[locale]/legal/[doc]">) {
  const { locale, doc: key } = await params;
  const doc = docs[key];
  if (!isLocale(locale) || !doc) notFound();

  return (
    <Section>
      <article className="mx-auto max-w-3xl">
        <p className="overline">{company.brand}</p>
        <h1 className="mt-2 font-display text-3xl font-bold uppercase tracking-[-0.01em] text-fg md:text-4xl">
          {doc.title}
        </h1>
        <p className="mt-3 text-sm text-fg-subtle">Редакция от {EDITION}</p>

        <p className="mt-8 text-base leading-7 text-fg-muted">{doc.intro}</p>

        {doc.sections.map((section) => (
          <section key={section.heading} className="mt-10">
            <h2 className="font-display text-lg font-semibold text-fg">
              {section.heading}
            </h2>
            <ul className="mt-4 space-y-3">
              {section.items.map((item) => (
                <li
                  key={item}
                  className="relative pl-5 text-sm leading-6 text-fg-muted before:absolute before:left-0 before:top-[0.6em] before:h-1.5 before:w-1.5 before:rounded-full before:bg-coral"
                >
                  {item}
                </li>
              ))}
            </ul>
          </section>
        ))}

        <section className="mt-12 rounded-card border border-line p-6">
          <h2 className="font-display text-lg font-semibold text-fg">
            Реквизиты
          </h2>
          <Requisites />
        </section>
      </article>
    </Section>
  );
}

export function Requisites({ compact = false }: { compact?: boolean }) {
  return (
    <dl
      className={`mt-4 grid gap-x-6 gap-y-2 ${compact ? "text-xs" : "text-sm"} sm:grid-cols-[max-content_1fr]`}
    >
      {requisiteRows.map(([label, value]) => (
        <div key={label} className="contents">
          <dt className="text-fg-subtle">{label}</dt>
          <dd className="break-words text-fg-muted">{value}</dd>
        </div>
      ))}
    </dl>
  );
}
